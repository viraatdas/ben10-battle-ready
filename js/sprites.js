// Render a sprite to a cached canvas image
function renderSprite(spriteData, scale, flipH) {
    const key = JSON.stringify(spriteData.palette) + scale + (flipH ? 'f' : '');
    if (SpriteCache[key]) return SpriteCache[key];

    const pixels = spriteData.idle;
    const w = spriteData.w * scale;
    const h = pixels.length * scale;
    const c = createCanvas(w, h);
    const ctx = c.getContext('2d');

    if (flipH) {
        ctx.translate(w, 0);
        ctx.scale(-1, 1);
    }

    drawPixelChar(ctx, 0, 0, scale, pixels, spriteData.palette);
    SpriteCache[key] = c;
    return c;
}

// Render simple animation frame (offset the sprite slightly)
function renderAnimFrame(spriteData, scale, frame, flipH) {
    const c = renderSprite(spriteData, scale, flipH);
    return { img: c, offsetY: Math.sin(frame * 0.15) * 2 };
}
